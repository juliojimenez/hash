#!/usr/bin/env bash
# Write book/src/conformance.md, the smoosh conformance figure the site shows,
# from the latest successful run of the smoosh workflow on main. The site build
# runs this before mdbook so the figure is what CI measured, not what someone
# typed. Without gh, a token, or a run to read, the committed file is kept.
#
# Usage: bash scripts/conformance-figure.sh [repo]      (default: $GITHUB_REPOSITORY or juliojimenez/hash)
set -u

repo="${1:-${GITHUB_REPOSITORY:-juliojimenez/hash}}"
cd "$(cd "$(dirname "$0")" && pwd)/.."
out=book/src/conformance.md

keep() { echo "conformance-figure: $*; keeping $out"; exit 0; }
command -v gh >/dev/null 2>&1 || keep "gh is not installed"

run=$(gh run list -R "$repo" --workflow posix.yml --branch main --status success -L 1 \
        --json databaseId,headSha,createdAt --jq '.[0] | "\(.databaseId) \(.headSha) \(.createdAt)"' 2>/dev/null) || run=""
[ -n "$run" ] || keep "no successful smoosh run on main could be read"
set -- $run
id=$1; sha=$2; when=${3%%T*}

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
gh run download -R "$repo" "$id" -n smoosh-test-results -D "$tmp" >/dev/null 2>&1 || keep "the results of run $id could not be downloaded"
summary=$(find "$tmp" -name summary.txt | head -1)
[ -n "$summary" ] || keep "run $id has no summary.txt"

field() { awk -v k="$1:" '$1 == k { print $2 }' "$summary"; }
total=$(field Total); passed=$(field Passed); failed=$(field Failed); skipped=$(field Skipped); timeout=$(field Timeout)
[ -n "$total" ] && [ -n "$passed" ] || keep "run $id has an unreadable summary"
failing=$(( ${failed:-0} + ${timeout:-0} ))
case ${skipped:-0} in
    0) skipped_text="" ;;
    1) skipped_text=", 1 skipped on purpose ([why](https://github.com/juliojimenez/hash/issues/314))" ;;
    *) skipped_text=", $skipped skipped on purpose" ;;
esac

cat > "$out" <<MD
<!-- Generated by scripts/conformance-figure.sh from the smoosh run on main. Do not edit. -->
**$passed of $total** [smoosh](https://github.com/mgree/smoosh) POSIX tests pass${skipped_text}, $failing failing.
CI measured this on commit [\`${sha:0:7}\`](https://github.com/$repo/commit/$sha) on $when ([the run](https://github.com/$repo/actions/runs/$id)).
MD
echo "conformance-figure: $passed of $total, $failing failing, from run $id (${sha:0:7}, $when)"
