#!/usr/bin/env bash
# Prepare a release of hash: bump every version string in the tree and add the
# Debian changelog entry. Review the diff, commit it as "chore(release): vNN",
# merge, then push the tag; .github/workflows/release.yml does the rest (see
# "Cutting a Release" in CONTRIBUTING.md).
#
# Usage: bash scripts/release.sh <version> [--pr]     e.g. bash scripts/release.sh 47
#        make release VERSION=<version>
#
# --pr also creates the branch release/vNN, commits (signed-off) and opens the
# pull request.

set -euo pipefail

die() { echo "release: $*" >&2; exit 1; }

new=""
open_pr=false
for arg in "$@"; do
    case "$arg" in
        --pr) open_pr=true ;;
        -h|--help) sed -n '2,11p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) new="$arg" ;;
    esac
done
new="${new#v}"
[[ "$new" =~ ^[0-9]+$ ]] || die "usage: bash scripts/release.sh <version> [--pr]   (an integer, e.g. 47)"

cd "$(git rev-parse --show-toplevel)"
old=$(sed -n 's/^#define HASH_VERSION "\([0-9][0-9]*\)".*/\1/p' src/hash.h)
[ -n "$old" ] || die "cannot read HASH_VERSION from src/hash.h"
[ "$new" -gt "$old" ] 2>/dev/null || die "version $new is not above the current version $old"
git diff --quiet && git diff --cached --quiet || die "the working tree has changes; commit or stash them first"
git rev-parse -q --verify "refs/tags/v$old" >/dev/null || die "tag v$old is missing; run: git fetch --tags"

export OLD="$old" NEW="$new"

# The source of truth, and the FreeBSD port skeleton that mirrors it
perl -pi -e 's/^#define HASH_VERSION "$ENV{OLD}"/#define HASH_VERSION "$ENV{NEW}"/' src/hash.h
perl -pi -e 's/^(DISTVERSION=\s*)$ENV{OLD}$/$1$ENV{NEW}/' freebsd/Makefile

# Every other tracked text file that mentions the old version: download URLs
# and sample output (vNN), Debian package names (_NN-1, NN-1~), the man page
# header (hash-shell NN) and prose ("version NN", `NN`). debian/changelog keeps its
# history, SECURITY.md keeps a window of versions (below) and the built book is
# regenerated by CI.
{ git grep -I -l -E "v$old|$old-1|hash-shell $old|version $old|\`$old\`" -- . \
      ':!debian/changelog' ':!SECURITY.md' ':!book/output' ':!scripts/release.sh' || true; } |
while IFS= read -r file; do
    perl -pi -e '
        s/\bv$ENV{OLD}\b/v$ENV{NEW}/g;
        s/hash-shell_$ENV{OLD}-1/hash-shell_$ENV{NEW}-1/g;
        s/\b$ENV{OLD}-1~/$ENV{NEW}-1~/g;
        s/hash-shell $ENV{OLD}\b/hash-shell $ENV{NEW}/g;
        s/version $ENV{OLD}\b/version $ENV{NEW}/g;
        s/`$ENV{OLD}`/`$ENV{NEW}`/g;
    ' "$file"
done

# Man page header: version and month
MONTH=$(LC_ALL=C date '+%B %Y') perl -pi -e \
    's/^(\.TH HASH-SHELL 1 )"[A-Za-z]+ [0-9]{4}"/$1"$ENV{MONTH}"/' debian/hash-shell.1

# SECURITY.md lists the five most recent releases as supported
DROP=$((new - 5)) FLOOR=$((new - 4)) perl -pi -e '
    if (!$done && /^\| v[0-9]+\.x\s+\|/) { print "| v$ENV{NEW}.x   | :white_check_mark: |\n"; $done = 1 }
    $_ = "" if /^\| v$ENV{DROP}\.x\s+\|/;
    s/^\| < v[0-9]+(\s+\|)/| < v$ENV{FLOOR}$1/;
' SECURITY.md

# Debian changelog entry: the commits since the last release, dependency bumps
# left out, the author named when it is not the maintainer
maintainer=$(sed -n 's/^ -- \(.*>\)  .*/\1/p' debian/changelog | head -1)
[ -n "$maintainer" ] || die "cannot read the maintainer line from debian/changelog"
entries=$(git log --no-merges --format='%s%x09%an' "v$old..HEAD" |
    awk -F'\t' -v me="${maintainer% <*}" '
        $1 ~ /^chore\((deps|release)\)/ { next }
        { sub(/ \(#[0-9]+\)$/, "", $1); printf "  * %s%s\n", $1, ($2 == me ? "" : " (by " $2 ")") }')
[ -n "$entries" ] || entries="  * Maintenance release"
{
    printf 'hash-shell (%s-1) unstable; urgency=medium\n\n%s\n\n -- %s  %s\n\n' \
        "$new" "$entries" "$maintainer" "$(LC_ALL=C date '+%a, %d %b %Y %H:%M:%S %z')"
    cat debian/changelog
} > debian/changelog.new
mv debian/changelog.new debian/changelog

echo "release: v$old -> v$new"
git --no-pager diff --stat
left=$(git grep -I -n -E "(^|[^0-9A-Za-z_])v$old([^0-9]|$)|hash-shell_$old-1|(^|[^0-9])$old-1~|DISTVERSION=[[:space:]]*$old$|\`$old\`" -- . \
    ':!debian/changelog' ':!SECURITY.md' ':!book/output' ':!scripts/release.sh' || true)
if [ -n "$left" ]; then
    printf '\nrelease: these lines still mention v%s, check them by hand:\n%s\n' "$old" "$left"
fi

if $open_pr; then
    git checkout -q -b "release/v$new"
    git commit -q -s -a -m "chore(release): v$new"
    gh pr create --title "chore(release): v$new" \
        --body "$(printf '## Description\n\nRelease v%s.\n\n%s\n\n## Type of Change\n\n- [x] `chore` - Maintenance tasks\n' "$new" "$entries")"
else
    cat <<NEXT

Next:
  git diff                                   # review; edit debian/changelog if you like
  git checkout -b release/v$new && git commit -sam "chore(release): v$new"
  gh pr create --title "chore(release): v$new"
After the merge:
  git fetch origin && git tag -a v$new -m v$new origin/main && git push origin v$new
The tag push runs release.yml: binaries, GitHub release, then the Debian, Docker and Homebrew workflows.
NEXT
fi
